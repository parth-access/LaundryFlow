/**
 * Write the query registry (src/lib/queries.js) out as a .sql file.
 *
 *   npm run queries:export                      -> prints to the terminal
 *   npm run queries:export -- path/to/04_queries.sql   -> writes that file
 *
 * For the DE submission, point it at the AP repo's dbms folder, e.g.
 *   npm run queries:export -- ../LaundryFlow_AP_2026/dbms/04_queries.sql
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { QUERIES } from "../src/lib/queries.js";

const header = [
  "-- LaundryFlow: SQL queries used by the application",
  "-- Generated by `npm run queries:export` from src/lib/queries.js. Do not edit by hand:",
  "-- change the query in the app, then export again.",
  "-- $1, $2... are parameters supplied by the application.",
  "",
].join("\n");

const body = Object.values(QUERIES)
  .map((q) => {
    const params = q.params.length
      ? q.params.map((name, i) => `$${i + 1} = ${name}`).join(", ")
      : "none";
    return [
      `-- ${q.id}: ${q.title}`,
      `-- ${q.purpose}`,
      `-- Parameters: ${params}`,
      `${q.text.trim()};`,
      "",
    ].join("\n");
  })
  .join("\n");

const output = `${header}\n${body}`;
const target = process.argv[2];

if (target) {
  const file = resolve(target);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, output);
  console.log(`Wrote ${Object.keys(QUERIES).length} queries to ${file}`);
} else {
  process.stdout.write(output);
}
